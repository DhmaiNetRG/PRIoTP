    bson0 = make_update_bson("replay_s","FRAG0_DATA",seq_no=9,frag_no=0,frag_total=2,fragmented=True)
    pkt0  = priotps_encrypt(bson0,KEY,KEY_ID,seq_no=9,frag_no=0,frag_total=2)

    # Build tampered SEH claiming frag_no=1 but keep frag_no=0 ciphertext
    tampered_seh = build_seh(KEY_ID, FLAGS_FRAG_F, build_nonce(9,0,1,2))
    tampered     = tampered_seh + pkt0[SEH_SIZE:]
    info("Sending replay packet: SEH says frag_no=1 but ciphertext is from frag_no=0")

    udp_send(tampered, SERVER_IP, cp)
    settle(1.5)

    alive_ok = srv.alive()
    record(alive_ok, "Server did not crash on replayed packet")

    rej = srv.grep("rejected","auth","tag","failure","PRIoTPS")
    if rej:
        ok(f"Server logged rejection: {rej[0]}")
        record(True, "Server correctly rejected cross-fragment replay")
    else:
        warn("Rejection not found in stdout log (may be in stderr); checking alive")
        record(alive_ok, "Server survived — replay silently dropped (correct)")

    srv.stop()
    remove_psk_conf()

