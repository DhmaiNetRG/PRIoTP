def sensor_send(text: str, ip: str, port: int):
    msg = {
        "dev_id":      "temp_test",
        "ts":          str(round(time.time(), 3)),
        "seq_no":      str(int(time.time() * 1000) & 0xFFFF),
        "data_size":   str(len(text)),
        "sensor_data": text,
    }
    payload = str(msg).encode("utf-8")
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try: s.sendto(payload, (ip, port))
    finally: s.close()

def sensor_burst(text: str, ip: str, port: int, count=4, delay=0.25):
    for _ in range(count):
        sensor_send(text, ip, port)
        time.sleep(delay)

