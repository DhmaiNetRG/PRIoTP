def check_prerequisites():
    print("\n--- Checking prerequisites ---")
    ok_count = 0
    for path, label in [(SERVER_BIN,"PRTP_server"),(CLIENT_BIN,"PRTP_client"),
                        (CLIENTS_CONF,"test.conf"),(SENSOR_LIST,"sensor.list")]:
        if os.path.exists(path):
            ok(f"{label}  ->  {path}"); ok_count += 1
        else:
            fail(f"{label} NOT FOUND at {path}")
    if ok_count < 2:
        print("\n  ERROR: Required binaries missing. Build PRTP first."); sys.exit(1)

def _menu():
    print("\nSelect test(s) to run:")
    print("  A  Run all tests (T1-T9)")
    print("  U  Run non-interactive tests only (T2-T9, no user input required)")
    for i,(name,_) in enumerate(TESTS,1):
        print(f"  {i}  {name}")
    print("  Q  Quit")
    return input("\nChoice: ").strip().upper()

def main():
    print("="*64)
    print("  PRIoTPS End-to-End Test Suite")
    print("  Phases 3-6  |  PRTP_server + PRTP_client + PRIoTPS")
    print("="*64)
    print(f"  Server binary : {SERVER_BIN}")
    print(f"  Client binary : {CLIENT_BIN}")
    print(f"  Port strategy : unique pair per test (base={PORT_BASE})")

    check_prerequisites()

    if "--all" in sys.argv:
        for i,(_, fn) in enumerate(TESTS,1): fn(tidx=i)
        summary(); return

    while True:
        ch = _menu()
        if ch == "Q":
            summary(); break
        elif ch == "A":
            for i,(_,fn) in enumerate(TESTS,1): fn(tidx=i)
            summary(); break
        elif ch == "U":
            for i,(_,fn) in enumerate(TESTS[1:],2): fn(tidx=i)
            summary(); break
        elif ch.isdigit() and 1 <= int(ch) <= len(TESTS):
            i = int(ch)
            TESTS[i-1][1](tidx=i)
            summary()
        else:
            warn("Invalid choice. Try again.")

if __name__ == "__main__":
    main()
