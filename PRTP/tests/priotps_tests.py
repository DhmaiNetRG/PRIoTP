class PRTPProc:
    def __init__(self, cmd, name):
        self.name = name
        self.proc = None
        self._log  = []
        self._lock = threading.Lock()
        try:
            self.proc = subprocess.Popen(
                cmd, cwd=APP_DIR,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                bufsize=1, text=True,
            )
            threading.Thread(target=self._reader, daemon=True).start()
            info(f"[{self.name}] started  PID={self.proc.pid}")
        except Exception as e:
            fail(f"[{self.name}] failed to start: {e}")

    def _reader(self):
        for line in self.proc.stdout:
            with self._lock:
                self._log.append(line.rstrip())

    def log(self):
        with self._lock: return list(self._log)

    def grep(self, *patterns):
        out = []
        for line in self.log():
            for p in patterns:
                if p.lower() in line.lower():
                    out.append(line)
                    break
        return out

    def alive(self):
        return self.proc is not None and self.proc.poll() is None

    def stop(self):
        if self.proc and self.proc.poll() is None:
            try:
                self.proc.send_signal(signal.SIGTERM)
                self.proc.wait(timeout=4)
            except Exception:
                try: self.proc.kill()
                except Exception: pass
        info(f"[{self.name}] stopped (exit={self.proc.returncode if self.proc else 'N/A'})")

