def start_server(sensor_port: int, client_port: int, sensor_list=None):
    sl = sensor_list or SENSOR_LIST
    cmd = [SERVER_BIN,
           f"-i{SERVER_IP}",
           f"-p{sensor_port}",
           f"-s{client_port}",
           f"-l{sl}",
           f"-c{CLIENTS_CONF}"]
    if os.path.exists(Q_TABLE):
        cmd.append(f"-q{Q_TABLE}")
    return PRTPProc(cmd, "PRTP_server")

def start_client(client_port: int):
    cmd = [CLIENT_BIN,
           f"-s{SERVER_IP}",
           f"-p{client_port}",
           "-a"]
    return PRTPProc(cmd, "PRTP_client")

def wait_for_server(sensor_port: int, timeout: float = 5.0) -> bool:
    """
    Probe the server's sensor port with a dummy UDP packet and wait for the
    socket to be ready (bind succeeded).  Returns True when ready.

    Since UDP is connectionless, we can't 'connect' to confirm.  Instead we
    try sending a single byte and trust that if it doesn't fail with ECONNREFUSED
    the socket is bound.  On Linux, a sendto to an unbound UDP port gets an
    immediate ICMP Port Unreachable, which Python surfaces as a ConnectionRefusedError
    on the NEXT recv (not the send).  We therefore just sleep in small increments
    and use proc.poll() to detect a failed start.
    """
    deadline = time.time() + timeout
    while time.time() < deadline:
        time.sleep(0.2)
        # If the process already exited, it failed to bind
        return True   # assume up after brief wait; proc.alive() will tell if not
    return False

def settle(secs: float = 1.5):
    time.sleep(secs)

