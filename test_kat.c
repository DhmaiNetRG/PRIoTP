#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "PRTP/src/ascon.h"

int main() {
    uint8_t key[16] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f};
    uint8_t nonce[16] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f};
    uint8_t expected_tag[16] = {0xE3,0x55,0x15,0x9F,0x29,0x29,0x11,0xF7,0x94,0xCB,0x14,0x32,0xA0,0x10,0x3A,0x8A};
    
    uint8_t ct[16];
    ascon_aead128_encrypt(ct, NULL, 0, NULL, 0, nonce, key);
    
    printf("Expected tag: ");
    for(int i=0; i<16; i++) printf("%02x", expected_tag[i]);
    printf("\nComputed tag: ");
    for(int i=0; i<16; i++) printf("%02x", ct[i]);
    printf("\n");
    
    if (memcmp(ct, expected_tag, 16) == 0) {
        printf("KAT PASSED!\n");
        return 0;
    } else {
        printf("KAT FAILED!\n");
        return 1;
    }
}
