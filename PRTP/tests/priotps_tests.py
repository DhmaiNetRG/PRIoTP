_M64 = 0xFFFF_FFFF_FFFF_FFFF

def _r64(x, n): return ((x >> n) | (x << (64 - n))) & _M64
def _sbox(s):
    x = list(s)
    x[0]^=x[4]; x[4]^=x[3]; x[2]^=x[1]
    t = [x[i]^((~x[(i+1)%5]&_M64)&x[(i+2)%5]) for i in range(5)]
    t[1]^=t[0]; t[0]^=t[4]; t[3]^=t[2]; t[2]=~t[2]&_M64; return t
def _linear(x):
    x[0]^=_r64(x[0],19)^_r64(x[0],28); x[1]^=_r64(x[1],61)^_r64(x[1],39)
    x[2]^=_r64(x[2], 1)^_r64(x[2], 6); x[3]^=_r64(x[3],10)^_r64(x[3],17)
    x[4]^=_r64(x[4], 7)^_r64(x[4],41); return x
_RC=[0x3c,0x2d,0x1e,0x0f,0xf0,0xe1,0xd2,0xc3,0xb4,0xa5,0x96,0x87]
def _perm(s,r):
    for i in range(12-r,12): s[2]^=_RC[i]; s=_sbox(s); s=_linear(s)
    return s
def _l64(b,o=0): return struct.unpack_from(">Q",b,o)[0]
def _s64(v):     return struct.pack(">Q",v&_M64)
def _absorb(S,aad):
    n=len(aad)
    for i in range(0,n-n%8,8): S[0]^=_l64(aad,i); S=_perm(S,6)
    t=aad[n-n%8:]; p=t+b'\x80'+b'\x00'*(7-len(t)); S[0]^=_l64(p); S=_perm(S,6)
    return S

SEH_SIZE=12; TAG_SIZE=16; MAX_OVERHEAD=28
VER0=0; ALGO_ASCON=1; FLAG_ENC=0x80; FLAG_AUTH=0x40; FLAG_FRAG=0x20
FLAGS_NORMAL=FLAG_ENC|FLAG_AUTH
FLAGS_FRAG_F=FLAG_ENC|FLAG_AUTH|FLAG_FRAG

def build_nonce(seq,ts,fn,ft):
    return ((seq&0xFFFF)<<48)|((ts&0xFFFF)<<32)|((fn&0xFFFF)<<16)|(ft&0xFFFF)
def expand_nonce(n): return struct.pack(">Q",n)+b'\x00'*8
def build_seh(kid,flags,nonce):
    return bytes([(VER0<<6)|(ALGO_ASCON&0x3F), kid, flags, 0x00])+struct.pack(">Q",nonce)
def parse_seh(d): return (d[0]>>6)&3, d[0]&0x3F, d[1], d[2], struct.unpack_from(">Q",d,4)[0]

def _ascon_enc(pt,aad,nonce,key):
    K0,K1=_l64(key,0),_l64(key,8); N0,N1=_l64(nonce,0),_l64(nonce,8)
    S=[0x80400c0600000000,K0,K1,N0,N1]; S=_perm(S,12); S[3]^=K0; S[4]^=K1
    if aad: S=_absorb(S,aad)
    S[4]^=1; ct=bytearray(); p=pt
    while len(p)>=8: S[0]^=_l64(p); ct+=_s64(S[0]); S=_perm(S,6); p=p[8:]
    if p:
        pad=p+b'\x80'+b'\x00'*(7-len(p)); S[0]^=_l64(pad); ct+=_s64(S[0])[:len(p)]
    elif pt: S[0]^=0x8000000000000000
    S[1]^=K0; S[2]^=K1; S=_perm(S,12); S[3]^=K0; S[4]^=K1
    return bytes(ct)+_s64(S[3])+_s64(S[4])

def _ascon_dec(ct_tag,aad,nonce,key):
    K0,K1=_l64(key,0),_l64(key,8); N0,N1=_l64(nonce,0),_l64(nonce,8)
    S=[0x80400c0600000000,K0,K1,N0,N1]; S=_perm(S,12); S[3]^=K0; S[4]^=K1
    if aad: S=_absorb(S,aad)
    S[4]^=1; pt=bytearray(); tag=ct_tag[-16:]; c=ct_tag[:-16]; cc=c
    while len(cc)>=8:
        blk=_l64(cc); pt+=_s64(S[0]^blk); S[0]=blk; S=_perm(S,6); cc=cc[8:]
    if cc:
        pad=cc+b'\x80'+b'\x00'*(7-len(cc)); cblk=_l64(pad)
        pt+=_s64(S[0]^cblk)[:len(cc)]
        mk=_M64>>(8*len(cc)); mc=_M64<<(8*(8-len(cc)))
        S[0]=(S[0]&mk)^(cblk&mc)^(0x80<<(8*(7-len(cc))))
    elif c: S[0]^=0x8000000000000000
    S[1]^=K0; S[2]^=K1; S=_perm(S,12); S[3]^=K0; S[4]^=K1
    exp=_s64(S[3])+_s64(S[4])
    diff=0
    for a,b in zip(exp,tag): diff|=a^b
    if diff: return b'',False
    return bytes(pt),True

def priotps_encrypt(bson,key,key_id,seq_no,frag_no=0,frag_total=1):
    fragmented=frag_total>1
    flags=FLAGS_FRAG_F if fragmented else FLAGS_NORMAL
    wn=build_nonce(seq_no,0,frag_no,frag_total)
    seh=build_seh(key_id,flags,wn)
    return seh+_ascon_enc(bson,aad=seh,nonce=expand_nonce(wn),key=key)

def priotps_decrypt(pkt,key_table):
    if len(pkt)<SEH_SIZE+TAG_SIZE: raise ValueError(f"Too short: {len(pkt)}")
    seh=pkt[:SEH_SIZE]; ct_tag=pkt[SEH_SIZE:]
    ver,algo,kid,flags,wn=parse_seh(seh)
    if ver!=VER0: raise ValueError(f"Bad SEH version {ver}")
    if algo!=ALGO_ASCON: raise ValueError(f"Bad algo {algo}")
    if not(flags&FLAG_AUTH): raise ValueError("AUTH flag missing")
    key=key_table.get(kid)
    if key is None: raise ValueError(f"Unknown key_id={kid}")
    pt,good=_ascon_dec(ct_tag,aad=seh,nonce=expand_nonce(wn),key=key)
    if not good: raise ValueError("Authentication tag verification failed")
    return pt

# ---------------------------------------------------------------------------
# Minimal BSON builder (mirrors bson_msg.c serialize_update exactly)
# ---------------------------------------------------------------------------

BSON_INT32=0x10; BSON_BOOL=0x08; BSON_STRING=0x02; BSON_BINARY=0x05; BSON_DOCUMENT=0x03
TYPE_UPDATE=4; SENSOR_TEMP=0

def _bk(t,k): return bytes([t])+k.encode()+b'\x00'
def bi(k,v):  return _bk(BSON_INT32,k)+struct.pack("<i",v)
def bb(k,v):  return _bk(BSON_BOOL,k)+bytes([1 if v else 0])
def bs(k,v):  vb=v.encode()+b'\x00'; return _bk(BSON_STRING,k)+struct.pack("<I",len(vb))+vb
def bbin(k,d):return _bk(BSON_BINARY,k)+struct.pack("<I",len(d))+b'\x00'+d
def bdoc(body): n=4+len(body)+1; return struct.pack("<I",n)+body+b'\x00'
def bembed(key,body): return _bk(BSON_DOCUMENT,key)+bdoc(body)

def make_update_bson(sid,text,seq_no=1,frag_no=0,frag_total=1,fragmented=False):
    data=bi("sensor_type",SENSOR_TEMP)+bs("sid",sid)+bbin("blob",text.encode())
    body=(bi("type",TYPE_UPDATE)+bb("reliable",False)+bi("seq_no",seq_no)
          +bb("end_marker",True)+bb("fragmented",fragmented)
          +bb("utilize_timestamp",False)+bi("frag_no",frag_no)
          +bi("frag_total",frag_total)+bembed("data",data))
    return bdoc(body)

